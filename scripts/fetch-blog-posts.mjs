#!/usr/bin/env node
/**
 * Fetches Montasir's Medium RSS feed and writes it to
 * src/assets/data/blog.data.js as a plain JS module, the same way
 * projects.data.js is authored by hand.
 *
 * Runs automatically before `npm start` / `npm run build` (see package.json).
 * Network failures never break dev/build — the script just leaves whatever
 * blog.data.js already exists on disk untouched and exits cleanly.
 */
import { writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const FEED_URL = "https://medium.com/feed/@mmcse19";
const OUT_FILE = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src/assets/data/blog.data.js"
);
const MAX_POSTS = 6;

const decodeEntities = (str = "") =>
  str
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(parseInt(dec, 10)))
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&nbsp;/g, " ");

const stripTags = (html = "") => decodeEntities(html.replace(/<[^>]*>/g, " ")).replace(/\s+/g, " ").trim();

const between = (xml, tag) => {
  const match = xml.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)<\\/${tag}>`, "i"));
  if (!match) return "";
  return match[1].replace(/^<!\[CDATA\[/, "").replace(/\]\]>$/, "").trim();
};

const firstImageSrc = (html = "") => {
  const match = html.match(/<img[^>]*src="([^"]+)"/i);
  return match ? match[1] : "";
};

const truncate = (text, max = 180) =>
  text.length > max ? `${text.slice(0, max - 3).trim()}…` : text;

// Cross-posted stories carry a short teaser in <description>. Self-published
// stories carry the full body in <content:encoded> instead, so the first real
// paragraph (skipping the lead <figure> image) becomes the snippet.
const snippetFrom = (description = "", contentEncoded = "") => {
  const teaser = stripTags(description).replace(/Continue reading on [^»]*»?\s*$/i, "").trim();
  if (teaser.length > 20) return truncate(teaser);

  const firstParagraph = contentEncoded.match(/<p[^>]*>([\s\S]*?)<\/p>/i);
  if (firstParagraph) return truncate(stripTags(firstParagraph[1]));
  return "";
};

// Only self-published stories give us the real article body to estimate from
// — cross-posted teasers are too short to mean anything, so we skip them.
const readTimeFrom = (contentEncoded = "") => {
  if (!contentEncoded) return null;
  const words = stripTags(contentEncoded).split(/\s+/).filter(Boolean).length;
  return words > 0 ? Math.max(1, Math.round(words / 200)) : null;
};

const formatDate = (pubDate) => {
  const d = new Date(pubDate);
  if (Number.isNaN(d.getTime())) return pubDate;
  return d.toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
};

const parseItems = (xml) => {
  const items = xml.match(/<item>[\s\S]*?<\/item>/g) || [];
  return items.slice(0, MAX_POSTS).map((item) => {
    const title = decodeEntities(between(item, "title"));
    const link = between(item, "link").split("?source=")[0];
    const pubDate = between(item, "pubDate");
    const description = between(item, "description");
    const contentEncoded = between(item, "content:encoded");
    const categories = (item.match(/<category>([\s\S]*?)<\/category>/g) || [])
      .map((c) => decodeEntities(c.replace(/<\/?category>/g, "").replace(/^<!\[CDATA\[/, "").replace(/\]\]>$/, "").trim()))
      .filter(Boolean)
      .slice(0, 2);

    return {
      title,
      link,
      date: formatDate(pubDate),
      thumbnail: firstImageSrc(description) || firstImageSrc(contentEncoded),
      snippet: snippetFrom(description, contentEncoded),
      tags: categories,
      readTimeMinutes: readTimeFrom(contentEncoded),
    };
  });
};

const toModuleSource = (posts) => {
  const body = JSON.stringify(posts, null, 2)
    .replace(/^\[/, "[")
    .replace(/"([a-zA-Z0-9_]+)":/g, "$1:");
  return `// Auto-generated by scripts/fetch-blog-posts.mjs — do not edit by hand.
// Re-run \`npm run fetch:blog\` (or just \`npm start\` / \`npm run build\`) to refresh.
const BlogPosts = ${body};

export default BlogPosts;
`;
};

async function main() {
  let xml;
  try {
    const res = await fetch(FEED_URL, {
      headers: { "User-Agent": "Mozilla/5.0 (portfolio build script)" },
      signal: AbortSignal.timeout(10000),
    });
    if (!res.ok) throw new Error(`Medium responded ${res.status}`);
    xml = await res.text();
  } catch (err) {
    console.warn(`[fetch-blog-posts] Skipping refresh — could not reach Medium (${err.message}). Keeping existing blog.data.js.`);
    return;
  }

  try {
    const posts = parseItems(xml);
    if (!posts.length) {
      console.warn("[fetch-blog-posts] Feed returned no items, keeping existing blog.data.js.");
      return;
    }
    await writeFile(OUT_FILE, toModuleSource(posts), "utf8");
    console.log(`[fetch-blog-posts] Wrote ${posts.length} posts to ${path.relative(process.cwd(), OUT_FILE)}`);
  } catch (err) {
    console.warn(`[fetch-blog-posts] Failed to parse/write feed (${err.message}). Keeping existing blog.data.js.`);
  }
}

// Verify we can still read (or create) the target directory before doing network work.
readFile(OUT_FILE, "utf8").catch(() => {});
await main();
